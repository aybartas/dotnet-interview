using System.Reflection;
using System.Reflection.PortableExecutable;
using System.Runtime.InteropServices;
using Junior.BuildRunBasics.Shared;

namespace Junior.BuildRunBasics.BigPicture;

public static class Section01_DllAndApphost
{
    public static void Run()
    {
        var assembly = typeof(Samples).Assembly;
        var dll = assembly.Location;
        var dir = Path.GetDirectoryName(dll)!;
        var name = assembly.GetName().Name!;
        var apphost = Directory.EnumerateFiles(dir, name + "*").FirstOrDefault(f => Path.GetFileName(f) is var n && (n == name || n == name + ".exe"));

        Console.WriteLine("Pipeline summary:");
        Console.WriteLine("  C# source → [Roslyn] → .dll with IL + metadata → [MSBuild] bin/ folder → apphost → hostfxr → hostpolicy → CoreCLR → [JIT] native code → CPU\n");

        Console.WriteLine($"1) YOUR CODE IS ALWAYS A .dll: {Path.GetFileName(dll)}  ({ProjectLocator.HumanSize(new FileInfo(dll).Length)})");
        Describe("   ", dll);

        if (apphost is not null)
        {
            Console.WriteLine($"\n2) What we call the '.exe' is the APPHOST: {Path.GetFileName(apphost)}  ({ProjectLocator.HumanSize(new FileInfo(apphost).Length)})");
            Describe("   ", apphost);
            Console.WriteLine("   → It is a small, NATIVE launcher; it contains NO C# code of yours. Its only job: find the .NET runtime and start the .dll.");
        }
        else
        {
            Console.WriteLine("\n2) No apphost found in this folder (UseAppHost may be false; then it runs via 'dotnet <dll>').");
        }

        Console.WriteLine("\n3) Who is running right now?");
        Console.WriteLine($"   Environment.ProcessPath       : {Environment.ProcessPath}");
        Console.WriteLine($"   Running runtime                : {RuntimeInformation.FrameworkDescription}  ({RuntimeInformation.RuntimeIdentifier})");
        Console.WriteLine($"   Runtime folder (CoreCLR + BCL) : {RuntimeEnvironment_GetDirectory()}");
        Console.WriteLine($"   System.Private.CoreLib.dll     : {typeof(object).Assembly.Location}   ← object, string, List<T>... live in this .dll (BCL), which is IL too");
        Console.WriteLine($"   Entry point                    : {Assembly.GetEntryAssembly()!.EntryPoint!.DeclaringType!.Name}.{Assembly.GetEntryAssembly()!.EntryPoint!.Name} (top-level statements → generated by the compiler)");

        Console.WriteLine("""

        Startup chain (when you type 'MyApp'):
          1. apphost (MyApp / MyApp.exe)     → native; reads MyApp.runtimeconfig.json to learn which runtime/framework is required
          2. hostfxr                         → picks the right .NET version (roll-forward rules; from the machine-wide dotnet install)
          3. hostpolicy                      → resolves dependencies (assembly paths) from MyApp.deps.json
          4. CoreCLR (runtime)               → loads the .dll, starts memory/GC
          5. JIT                             → turns IL into machine code as methods are first called; the CPU runs it

        ⭐ "How does C# code become an .exe?" → IT DOESN'T. Your code lives in the .dll as IL; the .exe is just a small native launcher for that .dll
          (it also runs without the apphost via `dotnet MyApp.dll`). Translation to native code happens at run time via the JIT
          (exceptions: Native AOT / ReadyToRun → M2.5).
        """);
    }

    private static string RuntimeEnvironment_GetDirectory() => System.Runtime.InteropServices.RuntimeEnvironment.GetRuntimeDirectory();

    private static void Describe(string indent, string path)
    {
        var magic = new byte[4];
        using (var head = File.OpenRead(path)) _ = head.Read(magic, 0, 4);

        if (magic[0] == 'M' && magic[1] == 'Z')                          // Windows PE (both managed .dll and native apphost.exe)
        {
            using var stream = File.OpenRead(path);
            using var pe = new PEReader(stream);
            if (pe.HasMetadata)
            {
                var cor = pe.PEHeaders.CorHeader!;
                Console.WriteLine($"{indent}PE file: MANAGED — has a CLR header, ILOnly={(cor.Flags & CorFlags.ILOnly) != 0}, machine tag={pe.PEHeaders.CoffHeader.Machine} ('I386' is normal for AnyCPU IL; it does not mean 32-bit)");
                Console.WriteLine($"{indent}Contents are IL + metadata (type/method tables, strings); no CPU-specific machine code → platform independent.");
            }
            else
            {
                Console.WriteLine($"{indent}PE file: NATIVE — no CLR metadata (not managed), machine={pe.PEHeaders.CoffHeader.Machine}");
            }
        }
        else if (magic[0] == 0x7F && magic[1] == 'E' && magic[2] == 'L' && magic[3] == 'F')
        {
            Console.WriteLine($"{indent}ELF file (Linux): NATIVE executable — no CLR metadata; it holds no C# code, just a small launcher that finds and starts the runtime.");
        }
        else
        {
            Console.WriteLine($"{indent}Mach-O file (macOS): NATIVE executable — no CLR metadata; a small launcher that finds and starts the runtime.");
        }
    }
}
