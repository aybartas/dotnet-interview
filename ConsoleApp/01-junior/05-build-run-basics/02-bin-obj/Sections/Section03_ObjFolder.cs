using System.Security.Cryptography;
using System.Text.Json;
using Junior.BuildRunBasics.Shared;

namespace Junior.BuildRunBasics.BinObj;

public static class Section03_ObjFolder
{
    public static void Run()
    {
        var projectDir = ProjectLocator.FindProjectDirectory();
        if (projectDir is null)
        {
            Console.WriteLine("Project folder not found (the app may be running from a published copy: obj/ exists only on the development machine, next to the source).");
            return;
        }

        var obj = Path.Combine(projectDir, "obj");
        Console.WriteLine($"obj/ = intermediate output (restore result + files generated during the build): {obj}\n");

        Console.WriteLine("Root files:");
        foreach (var file in new DirectoryInfo(obj).EnumerateFiles().OrderBy(f => f.Name, StringComparer.Ordinal))
            Console.WriteLine($"   {file.Name,-52} {ProjectLocator.HumanSize(file.Length),9}  {DescribeRoot(file.Name)}");

        var config = new DirectoryInfo(AppContext.BaseDirectory.TrimEnd(Path.DirectorySeparatorChar)).Parent!.Name;   // bin/<config>/<tfm> → configuration of the running output
        var tfmDir = Directory.Exists(Path.Combine(obj, config)) ? new DirectoryInfo(Path.Combine(obj, config)).EnumerateDirectories().FirstOrDefault() : null;
        if (tfmDir is not null)
        {
            Console.WriteLine($"\nobj/{config}/{tfmDir.Name}/ (build intermediate output):");
            foreach (var file in tfmDir.EnumerateFiles().OrderBy(f => f.Name, StringComparer.Ordinal))
                Console.WriteLine($"   {file.Name,-52} {ProjectLocator.HumanSize(file.Length),9}  {DescribeIntermediate(file.Name)}");

            var objDll = Path.Combine(tfmDir.FullName, "ConsoleApp.dll");
            var binDll = Path.Combine(AppContext.BaseDirectory, "ConsoleApp.dll");
            if (File.Exists(objDll) && File.Exists(binDll))
                Console.WriteLine($"\nIs the .dll in obj the SAME as the .dll in bin? {Hash(objDll) == Hash(binDll)}   (the compiler writes to obj/ first; MSBuild COPIES to bin/)");

            var globalUsings = tfmDir.EnumerateFiles("*.GlobalUsings.g.cs").FirstOrDefault();
            if (globalUsings is not null)
                Console.WriteLine($"\n{globalUsings.Name} — the real face of ImplicitUsings (global usings in effect in every .cs file):\n{Indent(File.ReadAllText(globalUsings.FullName))}");
        }

        var assets = Path.Combine(obj, "project.assets.json");
        if (File.Exists(assets))
        {
            using var doc = JsonDocument.Parse(File.ReadAllText(assets));
            var targets = doc.RootElement.GetProperty("targets").EnumerateObject().Select(t => t.Name);
            var folders = doc.RootElement.GetProperty("packageFolders").EnumerateObject().Select(f => f.Name);
            Console.WriteLine($"project.assets.json summary: targets = {string.Join(", ", targets)}; NuGet package folder = {string.Join(", ", folders)}");
        }

        Console.WriteLine("""

        obj/ = MSBuild's workbench: the restore result (project.assets.json), props/targets generated by NuGet, AssemblyInfo, GlobalUsings, the intermediate .dll.
        bin/ = the final, distributable output. Both are GENERATED files → they go into .gitignore and are not committed. When something breaks, delete and regenerate them.
        """);
    }

    private static string Hash(string path) => Convert.ToHexString(SHA256.HashData(File.ReadAllBytes(path)));

    private static string Indent(string text) => string.Join('\n', text.Split('\n').Select(l => "      " + l.TrimEnd()).Where(l => l.Trim().Length > 0).Take(14));

    private static string DescribeRoot(string name) => name switch
    {
        "project.assets.json" => "★ restore result: resolved packages/dependency graph (the IDE and compiler read it)",
        _ when name.EndsWith(".nuget.g.props", StringComparison.Ordinal) => "MSBuild props generated by NuGet (settings contributed by packages)",
        _ when name.EndsWith(".nuget.g.targets", StringComparison.Ordinal) => "MSBuild targets generated by NuGet",
        _ when name.EndsWith(".nuget.dgspec.json", StringComparison.Ordinal) => "restore input (project/package graph summary)",
        _ when name.EndsWith(".nuget.cache", StringComparison.Ordinal) => "restore cache (restore is skipped if nothing changed)",
        _ => "?",
    };

    private static string DescribeIntermediate(string name) => name switch
    {
        _ when name.EndsWith(".AssemblyInfo.cs", StringComparison.Ordinal) => "GENERATED source fed to the compiler: assembly attributes (version, configuration)",
        _ when name.EndsWith(".GlobalUsings.g.cs", StringComparison.Ordinal) => "GENERATED source: ImplicitUsings → global using list",
        _ when name.EndsWith(".AssemblyInfoInputs.cache", StringComparison.Ordinal) => "incremental build cache",
        _ when name.EndsWith(".GeneratedMSBuildEditorConfig.editorconfig", StringComparison.Ordinal) => "analyzer settings generated from MSBuild properties",
        _ when name.EndsWith(".dll", StringComparison.Ordinal) => "★ intermediate .dll produced by the compiler (copied to bin/)",
        _ when name.EndsWith(".pdb", StringComparison.Ordinal) => "intermediate debug symbols",
        _ when name.EndsWith(".csproj.CoreCompileInputs.cache", StringComparison.Ordinal) => "incremental build: input summary",
        _ when name.EndsWith(".csproj.FileListAbsolute.txt", StringComparison.Ordinal) => "file list so that dotnet clean knows what to delete",
        "apphost" or "apphost.exe" => "project-specific copy of the apphost template (copied to bin/)",
        _ => "intermediate/generated file",
    };
}
