namespace Junior.CSharpFundamentals.ModernCSharp;

public static class Section09_Csharp14
{
    public static void Run()
    {
        Console.WriteLine("A) `field` keyword (C# 14): property validation without writing the backing field by hand");
        var p = new Product { Name = "  Pen  ", Price = 12.5m };
        Console.WriteLine($"   Name = \"{p.Name}\" (the setter trimmed it)");
        try { p.Price = -1m; }
        catch (ArgumentOutOfRangeException ex) { Console.WriteLine($"   Price = -1 → {ex.GetType().Name}"); }
        Console.WriteLine($"   OLD style: private string _name; public string Name {{ get => _name; set => _name = value.Trim(); }} — field + property + assignment (3 pieces)");
        Console.WriteLine($"   field keyword: inside a single property `field` is the hidden backing field generated by the compiler; no declaration.");
        Console.WriteLine("   ⚠ If your class already has a field/variable named 'field' the meaning changes: disambiguate with `@field` or `this.field` (the compiler issues a breaking-change warning).");

        Console.WriteLine("\nB) Null-conditional assignment (C# 14): `x?.Prop = value` — if x is null the assignment is NEVER performed (the right-hand side is not evaluated either)");
        Customer? customer = new() { Name = "old" };
        customer?.Name = "new";                                     // if customer were null: the assignment would be silently skipped
        Console.WriteLine($"   customer?.Name = \"new\" → {customer?.Name}");

        Customer? none = null;
        var evaluated = false;
        none?.Name = Expensive(ref evaluated);                      // none is null → the right-hand side (Expensive) is NOT CALLED
        Console.WriteLine($"   none?.Name = Expensive() → assignment skipped because it was null; was the right-hand side called? {evaluated}");
        Console.WriteLine("   Old style: if (customer != null) customer.Name = \"new\";  (both a line and noise)");
        Console.WriteLine("   Compound assignment works too: customer?.Count += 1;  ·  ++/-- are not supported.");

        Console.WriteLine("""

        Other C# 14 features (extension members, partial constructors/events, lambda parameter modifiers…) and the version-by-version history C# 8 → 15 → M1.1.
        C# 15 / .NET 11 features are mentioned in this repo only with the **(.NET 11)** marker.
        """);
    }

    private static string Expensive(ref bool evaluated) { evaluated = true; return "x"; }

    private sealed class Customer
    {
        public string Name { get; set; } = "";
        public int Count { get; set; }
    }

    private sealed class Product
    {
        public string Name
        {
            get;
            set => field = value?.Trim() ?? throw new ArgumentNullException(nameof(value));
        } = "";

        public decimal Price
        {
            get;
            set => field = value >= 0 ? value : throw new ArgumentOutOfRangeException(nameof(value));
        }
    }
}
